            double seatScarcityMultiplier = Math.pow(Math.max(0.1, 150.0 / Math.max(1.0, remainingSeats)), 0.65);
            double timeDecayPremium = Math.max(1.0, Math.min(2.5, 30.0 / Math.max(1.0, daysToDeparture)));
